/// The app's two typefaces.
abstract final class AppFonts {
  /// Body text, forms, tables and UI labels.
  static const body = 'OpenSans';

  /// Headings, page titles and the wordmark: a classical serif that suits a
  /// builder's brand.
  static const display = 'Cinzel';

  /// Fills in glyphs the two lack, notably the peso sign (₱).
  static const fallback = ['Roboto'];
}
